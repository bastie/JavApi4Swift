// MARK: - DoubleUnaryOperator

extension java.util.function {
  /// Represents an operation on a single `Double`-valued operand that produces a `Double` result.
  ///
  /// Primitive specialisation of ``UnaryOperator`` for `Double` (Java's `double`).
  /// Equivalent to `AnyUnaryOperator<Double>`.
  ///
  /// - Since: Java 8
  public typealias DoubleUnaryOperator = AnyUnaryOperator<Double>
}
