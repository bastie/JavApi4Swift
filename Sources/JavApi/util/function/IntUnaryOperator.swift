// MARK: - IntUnaryOperator

extension java.util.function {
  /// Represents an operation on a single `Int`-valued operand that produces an `Int` result.
  ///
  /// Primitive specialisation of ``UnaryOperator`` for `Int` (Java's `int`).
  /// Equivalent to `AnyUnaryOperator<Int>`.
  ///
  /// - Since: Java 8
  public typealias IntUnaryOperator = AnyUnaryOperator<Int>
}
